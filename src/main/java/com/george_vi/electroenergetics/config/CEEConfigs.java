package com.george_vi.electroenergetics.config;

import net.createmod.catnip.config.ConfigBase;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.ModLoadingContext;
import net.neoforged.fml.config.ModConfig;
import net.neoforged.fml.event.config.ModConfigEvent;
import net.neoforged.neoforge.common.ModConfigSpec;
import org.apache.commons.lang3.tuple.Pair;

import com.mojang.logging.LogUtils;
import org.slf4j.Logger;

import java.util.EnumMap;
import java.util.Map;
import java.util.function.Supplier;

public class CEEConfigs {

    private static final Map<ModConfig.Type, ConfigBase> CONFIGS = new EnumMap<>(ModConfig.Type.class);

    private static final Logger LOGGER = LogUtils.getLogger();

    private static CServer server;
    private static CClient client;

    public static CServer server() {
        return server;
    }

    public static CClient client() {
        return client;
    }

    public static ConfigBase byType(ModConfig.Type type) {
        return CONFIGS.get(type);
    }

    private static <T extends ConfigBase> T register(Supplier<T> factory, ModConfig.Type side) {
        Pair<T, ModConfigSpec> specPair = new ModConfigSpec.Builder().configure(builder -> {
            T config = factory.get();
            config.registerAll(builder);
            return config;
        });

        T config = specPair.getLeft();
        config.specification = specPair.getRight();
        CONFIGS.put(side, config);
        return config;
    }

    public static void register(ModLoadingContext context, ModContainer container) {
        client = register(CClient::new, ModConfig.Type.CLIENT);
        server = register(CServer::new, ModConfig.Type.SERVER);

        for (Map.Entry<ModConfig.Type, ConfigBase> pair : CONFIGS.entrySet())
            container.registerConfig(pair.getKey(), pair.getValue().specification);
    }

    @SubscribeEvent
    public static void onLoad(ModConfigEvent.Loading event) {
        for (ConfigBase config : CONFIGS.values())
            if (config.specification == event.getConfig()
                    .getSpec()) {
                config.onLoad();
                if (config == server)
                    logEffectiveTraction(false);
            }
    }

    @SubscribeEvent
    public static void onReload(ModConfigEvent.Reloading event) {
        for (ConfigBase config : CONFIGS.values())
            if (config.specification == event.getConfig()
                    .getSpec()) {
                config.onReload();
                if (config == server)
                    logEffectiveTraction(true);
            }
    }

    /**
     * Print the traction figures this session will actually use, and call out any key
     * whose loaded value differs from the code default.
     *
     * NeoForge keeps whatever value is already written in the config file when a mod
     * changes a default, so a config generated by an older build silently pins the old
     * figures next to a comment showing the new one. That once capped a train at 45
     * m/s while the code said 100, with nothing in the log hinting why. This makes the
     * effective settings visible in one place.
     */
    private static void logEffectiveTraction(boolean reload) {
        CTrains t = server.trainValues;
        LOGGER.info("[CEE] Effective traction settings ({}):", reload ? "reload" : "load");
        record Key(String name, double actual, double codeDefault, String unit) {}
        for (Key k : new Key[]{
                new Key("electricTrainMaxSpeed", t.electricTrainMaxSpeed.get(), 100d, "m/s"),
                new Key("electricTrainPowerPerCarriage", t.electricTrainPowerPerCarriage.get(), 1_375_000d, "W"),
                new Key("electricTrainMaxAcceleration", t.electricTrainMaxAcceleration.get(), 2.0d, "m/s2"),
                new Key("electricTrainBrakeDeceleration", t.electricTrainBrakeDeceleration.get(), 0.8d, "m/s2"),
                new Key("electricTrainDynamicBrakeMax", t.electricTrainDynamicBrakeMax.get(), 0.5d, "m/s2"),
                new Key("electricTrainHandoverSpeed", t.electricTrainHandoverSpeed.get(), 28d, "m/s"),
                new Key("electricTrainSeatGateSpeed", t.electricTrainSeatGateSpeed.get(), 28d, "m/s"),
                new Key("electricTrainPenaltySpeed", t.electricTrainPenaltySpeed.get(), 40d, "km/h"),
                new Key("electricTrainReverseMaxSpeed", t.electricTrainReverseMaxSpeed.get(), 10d, "m/s")}) {
            if (Math.abs(k.actual() - k.codeDefault()) > 1e-6d * Math.max(1, Math.abs(k.codeDefault())))
                LOGGER.warn("[CEE]   {} = {} {} (code default {} - the config file is pinning an older value)",
                        k.name(), k.actual(), k.unit(), k.codeDefault());
            else
                LOGGER.info("[CEE]   {} = {} {}", k.name(), k.actual(), k.unit());
        }
        // The derived figures a designer actually reasons with.
        int carriages = 1;
        double baseSpeed = com.george_vi.electroenergetics.content.railway_electrification.TrainTractionModel.baseSpeed(carriages);
        double holdGrade = com.george_vi.electroenergetics.content.railway_electrification.TrainTractionModel.maxHoldableGrade(
                com.george_vi.electroenergetics.content.railway_electrification.TrainTractionModel.frictionBrake());
        LOGGER.info("[CEE]   base speed (constant effort -> constant power) = {} m/s ({} km/h)",
                String.format("%.2f", baseSpeed), String.format("%.1f", baseSpeed * 3.6));
        LOGGER.info("[CEE]   steepest grade the service brake holds = {}% (rise over run)",
                String.format("%.1f", holdGrade * 100));
        LOGGER.info("[CEE]   regenerative braking {} (fraction {})",
                t.electricTrainRegenerativeBraking.get() ? "ON" : "OFF",
                t.electricTrainRegenerativeFraction.get());
    }
}
